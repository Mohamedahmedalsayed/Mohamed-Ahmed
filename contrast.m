function result = contrast(img, num_bits)
    % CONTRAST - Contrast stretching based on number of bits
    % INPUTS:
    %   img: Input image (grayscale or RGB)
    %   num_bits: Number of bits for intensity range (typically 1 to 8)
    %             1-bit: [0, 1]
    %             2-bit: [0, 3]
    %             3-bit: [0, 7]
    %             4-bit: [0, 15]
    %             5-bit: [0, 31]
    %             6-bit: [0, 63]
    %             7-bit: [0, 127]
    %             8-bit: [0, 255] (full range)
    % OUTPUT:
    %   result: Contrast stretched image
    
    % ?????? ?? ??? ??? ??????
    if num_bits < 1 || num_bits > 8 || ~isnumeric(num_bits) || num_bits ~= floor(num_bits)
        error('Number of bits must be an integer between 1 and 8');
    end
    
    % ???? ????? ?????? ????? ??? ??? ??????
    new_max = (2^num_bits) - 1;  % ?????? ??????
    new_min = 0;                 % ?????? ?????? (?????)
    
    fprintf('Contrast stretching: %d bits => Range [%d, %d]\n', num_bits, new_min, new_max);
    
    % ????? ?????? ??? double ???????? ????????
    if isinteger(img)
        img = double(img);
    else
        img = im2double(img);
        img = img * 255;  % ????? ?? [0,1] ??? [0,255] ??? ???? double
    end
    
    % ?????? ??? ????? ??????
    [H, W, L] = size(img);
    
    % ????? ?????? ???????
    result = zeros(H, W, L);
    
    % ???? ????? ??????
    new_range = new_max - new_min;
    
    % ????? Contrast Stretching ??? ?? ????
    for k = 1:L
        % ???? ????? ?????? ?????? ???????
        channel = img(:, :, k);
        old_min = min(channel(:));
        old_max = max(channel(:));
        old_range = old_max - old_min;
        
        % ??? ??? ????? ?????? ??? (???? ???????)
        if old_range == 0
            % ????? ???? ????? ??? ????? ????? ??????
            result(:, :, k) = (new_min + new_max) / 2;
            continue;
        end
        
        % ????? ???? Contrast Stretching
        for i = 1:H
            for j = 1:W
                % ??????: ((???? ?????? - old_min) / old_range) * new_range + new_min
                result(i, j, k) = ((channel(i, j) - old_min) / old_range) * new_range + new_min;
            end
        end
    end
    
    % ?? ????? ??? ????? ??????
    result = max(new_min, min(new_max, result));
    
    % ????? ??????? ??? uint8
    if new_max <= 255
        result = uint8(result);
    else
        result = uint16(result);
    end
    
    % ??? ???????
    fprintf('Original range: [%.2f, %.2f] -> New range: [%d, %d]\n', ...
            old_min, old_max, new_min, new_max);
end